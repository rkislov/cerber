package attack

func Rule(id string) *Assessment {
	a := assessment("rule_association", "")
	switch id {
	case "auth.repeated_failures":
		a.Observation = "Зафиксирована серия отказов входа; подбор пароля является гипотезой, возможны ошибки пользователя или службы."
		a.add("T1110.001", "Если отказы вызваны намеренным угадыванием пароля")
		a.effect("account_access", "При успешном подборе возможен доступ с правами этой учётной записи; возможна блокировка учётной записи политикой входа.", "Серия отказов не подтверждает знание пароля")
		a.Next = []string{"Проверить источник, пользователя и согласованные работы", "Проверить последующие успешные входы, тип входа и MFA"}
	case "auth.success_after_failures":
		a.Observation = "Зафиксирован успешный вход после отказов. Использование украденных или подобранных реквизитов не доказано."
		a.add("T1110.001", "Если серия отказов была подбором пароля")
		a.add("T1078", "Если успешный вход выполнен нарушителем с действующими реквизитами")
		a.effect("account_access", "Возможны действия с доступными учётной записи полномочиями; объём доступа зависит от её прав.", "Успешный вход наблюдался; личность и намерение оператора требуют проверки")
		a.Next = []string{"Сопоставить вход с владельцем учётной записи и IP/NAT", "Проверить процессы, изменения прав и дальнейшие действия этой сессии"}
	case "windows.audit_log_cleared":
		a.Observation = "Доставлено событие очистки журнала аудита Windows. Административное обслуживание не исключено."
		a.add("T1685.005", "Если журнал очищен для нарушения аудита или сокрытия активности")
		a.effect("visibility_loss", "Удалённые локальные записи могут быть недоступны для расследования. Сохранённые центральные события этим не удаляются.", "Событие Security 1102")
		a.Next = []string{"Установить инициатора и проверить заявку на обслуживание", "Сохранить центральные события и проверить соседние журналы"}
	case "firewall.port_scan", "firewall.syn_scan":
		a.Observation = "Наблюдались обращения к множеству портов. Согласованный сканер или иной легитимный процесс не исключены."
		a.add("T1046", "Для поиска служб внутри уже доступной сети")
		a.add("T1595", "Для внешней разведки перед возможным первоначальным доступом; расположение источника нужно установить")
		a.effect("service_discovery", "Источник может узнать доступные сервисы и выбрать дальнейшие цели. Доступ или эксплуатация не подтверждены.", "Различные порты в корреляционном окне")
		a.Next = []string{"Проверить назначенные сканирования Cerber и другие разрешённые сканеры", "Сопоставить адрес источника, доступные сервисы и последующие соединения"}
	case "firewall.denied_burst", "fess.blocked_burst":
		a.Observation = "Зафиксирована серия блокировок. Без содержимого запросов конкретная техника ATT&CK не определяется."
		a.effect("attempted_access", "При сохранении блокировки наблюдавшиеся попытки ограничены защитой; само событие не доказывает ущерб или отказ в обслуживании.", "Блокирующее действие источника")
		a.Next = []string{"Изучить тип запросов, URI/порты и лимиты защиты", "Проверить здоровье сервиса и наличие разрешённых запросов"}
	case "fess.allowed_after_blocks":
		a.Observation = "После блокировок зафиксировано разрешение запроса. Выполнение команды, обход WAF и эксплуатация не доказаны."
		a.effect("application_access", "Разрешённый запрос мог достичь приложения; возможный ущерб зависит от его содержимого и реакции приложения.", "Allow после deny не является доказательством успешной атаки")
		a.Next = []string{"Сопоставить requestId, URI, журналы приложения и HTTP-результат", "Искать признаки исполнения/изменений в системе перед выводом об эксплуатации"}
	case "threatfox.ioc_match", "threatfox.ip_match":
		a.Observation = "Событие совпало с индикатором ThreatFox. Роль IOC, направление соединения и актуальность инфраструктуры требуют проверки."
		a.effect("suspicious_indicator", "При подтверждении связи с вредоносной инфраструктурой возможна дальнейшая активность; совпадение IP, URL или хеша само не устанавливает C2, кражу данных или запуск файла.", "IOC-совпадение, а не наблюдение конкретной техники")
		a.Next = []string{"Проверить IOC, направление/порт и исходное событие", "Для файла проверить запуск процесса; для сети — процесс и назначение соединения"}
	default:
		return nil
	}
	return a
}
func Event(class, action, outcome, status string) *Assessment {
	if status != "parsed" {
		return nil
	}
	if class == "audit" && action == "log_cleared" {
		return Rule("windows.audit_log_cleared")
	}
	if class == "authentication" {
		a := assessment("event_context", "Одно событие входа не устанавливает технику ATT&CK или компрометацию.")
		if outcome == "success" {
			a.effect("account_access", "Наблюдался успешный вход. Последующие действия ограничены правами учётной записи; личность и намерение оператора требуют проверки.", "Исход входа success")
		} else if outcome == "failure" {
			a.effect("access_denied", "Эта попытка входа завершилась отказом; успешный доступ не подтверждён.", "Исход входа failure")
		}
		a.Next = []string{"Проверить контекст сессии и связанные корреляции"}
		return a
	}
	if class == "firewall" || class == "fess" {
		a := assessment("event_context", "Действие сетевой защиты само по себе не определяет технику ATT&CK.")
		switch action {
		case "deny":
			a.effect("blocked", "Наблюдалась блокировка; успешная эксплуатация или недоступность сервиса не установлены.", "Действие deny")
		case "allow":
			a.effect("allowed", "Наблюдалось разрешение. Обработка запроса приложением и последствия требуют отдельного подтверждения.", "Действие allow")
		case "syn":
			a.effect("connection_probe", "Наблюдался SYN; завершение TCP-соединения и доступ к сервису не подтверждены.", "Наблюдение SYN")
		}
		return a
	}
	return nil
}

func RuleVersion(id string, version int) *Assessment {
	if version != 1 {
		return nil
	}
	return Rule(id)
}
