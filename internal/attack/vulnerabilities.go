package attack

import (
	"strings"
)

func Vulnerability(ids []string, vector, status string) *Assessment {
	a := assessment("vulnerability_scenario", "Каталожная запись/версия — кандидат; применимость к установленному пакету требует проверки.")
	if status == "scanner_confirmed" {
		a.Observation = "Проверка сканера подтвердила признак уязвимости, но действия нарушителя и факт эксплуатации не установлены."
	} else if status == "context_required" {
		a.Observation = "Помимо версии не проверены дополнительные условия применимости из каталога."
	}
	metrics := map[string]string{}
	for _, part := range strings.Split(vector, "/") {
		p := strings.SplitN(part, ":", 2)
		if len(p) == 2 {
			metrics[p[0]] = p[1]
		}
	}
	for _, m := range []struct{ key, kind, text string }{{"C", "confidentiality", "Возможное раскрытие данных уязвимой системы"}, {"I", "integrity", "Возможное изменение данных или нарушение их целостности"}, {"A", "availability", "Возможное нарушение доступности уязвимого компонента"}, {"VC", "confidentiality", "Возможное раскрытие данных уязвимой системы"}, {"VI", "integrity", "Возможное изменение данных уязвимой системы"}, {"VA", "availability", "Возможное нарушение доступности уязвимой системы"}, {"SC", "subsequent_confidentiality", "Возможное раскрытие данных другой системы при выполнении условий эксплуатации"}, {"SI", "subsequent_integrity", "Возможное изменение данных другой системы при выполнении условий эксплуатации"}, {"SA", "subsequent_availability", "Возможное нарушение доступности другой системы при выполнении условий эксплуатации"}} {
		v := metrics[m.key]
		if v == "H" || v == "L" || v == "C" || v == "P" {
			a.Effects = append(a.Effects, Effect{Kind: m.kind, Extent: v, Description: m.text, Basis: "Потенциальное последствие по вектору CVSS: " + m.key + ":" + v})
		}
	}
	seen := map[string]bool{}
	for _, id := range ids {
		if seen[id] {
			continue
		}
		seen[id] = true
		switch id {
		case "CVE-2024-6387", "CVE-2017-0143", "CVE-2015-1635":
			a.add("T1190", "Возможный первоначальный доступ, если уязвимый сервис доступен из Интернета, уязвимость применима и эксплуатация успешна")
			a.add("T1210", "Возможное перемещение внутри сети, если нарушитель уже получил сетевую достижимость, а уязвимость применима")
			a.effect("code_execution", "Возможное выполнение кода в контексте уязвимого сервиса; права процесса и исправления пакета необходимо проверить.", "Проверенное сценарное соответствие Cerber для "+id+"; не наблюдение эксплуатации")
		case "CVE-2014-0160":
			a.effect("memory_disclosure", "Возможна утечка фрагментов памяти, включая чувствительные данные, если они находились в доступной памяти.", "Сценарий Heartbleed; утечка конкретных секретов не установлена")
		case "CVE-2014-3566", "CVE-2014-0224":
			a.add("T1557", "Сценарий требует положения посредника в трафике и уязвимой TLS-конфигурации; присутствие посредника не установлено")
			a.effect("traffic_disclosure", "При выполнении условий возможен доступ к защищаемому трафику. Возможность перехвата и конфигурацию TLS необходимо подтвердить.", "Сценарное соответствие для "+id)
		}
	}
	if len(a.Effects) == 0 {
		a.effect("unknown", "Для этой записи недостаточно структурированных данных для оценки последствий. Изучите описание и условия применимости.", "Нет поддерживаемого вектора CVSS или проверенного сценария")
	}
	if len(a.Techniques) == 0 {
		a.Limitations += " Для этой записи нет проверенного однозначного соответствия технике ATT&CK; техника не назначена по одной критичности или CWE."
	}
	a.Next = []string{"Проверить установленную версию пакета, исправления дистрибутива и условия эксплуатации", "Сопоставить доступность сервиса и его права с журналами процессов/сессий; искать подтверждения фактических действий"}
	return a
}
